import ClerkKit
import SwiftUI

struct ReverificationCodeView: View {
  @Environment(\.clerkTheme) private var theme
  @Environment(ReverificationFlow.self) private var flow
  @Environment(CodeLimiter.self) private var codeLimiter

  let factor: Factor
  let stage: ReverificationFlow.Stage

  @State private var code = ""
  @State private var error: Error?
  @State private var verificationState = CodeVerificationState.default
  @State private var otpFieldState: OTPField.FieldState = .default
  @FocusState private var otpFieldIsFocused: Bool

  private var sendsCode: Bool {
    factor.strategy != .totp
  }

  private var isPasswordReset: Bool {
    factor.isResetFactor
  }

  var body: some View {
    ScrollView {
      VStack(spacing: 0) {
        VStack(spacing: 8) {
          HeaderView(style: .title, text: "Verification required")
          HeaderView(style: .subtitle, text: subtitle)

          if let identifier = factor.safeIdentifier {
            IdentityPreviewView(label: identifier.formattedAsPhoneNumberIfPossible, isEnabled: false) {}
          }
        }
        .padding(.bottom, 32)

        VStack(spacing: 24) {
          OTPField(
            code: $code,
            fieldState: $otpFieldState,
            isFocused: $otpFieldIsFocused,
            accessibilityIdentifier: ClerkAccessibilityIdentifiers.Reverification.code
          ) { submittedCode in
            await attempt(code: submittedCode)
          }
          .onAppear {
            verificationState = .default
            otpFieldIsFocused = true
          }

          CodeVerificationStatusView(state: verificationState)

          if sendsCode, verificationState.showResend {
            ResendCodeButton(codeLimiter: codeLimiter, identifier: codeLimiterIdentifier, theme: theme) {
              await prepare()
            }
          }

          if !isPasswordReset {
            ReverificationUseAnotherMethodButton(factor: factor, stage: stage)
          }
        }
        .padding(.bottom, 32)

        SecuredByClerkView()
      }
      .padding(16)
    }
    #if os(iOS)
    .scrollDismissesKeyboard(.interactively)
    #endif
    .clerkErrorPresenting($error)
    .background(theme.colors.background)
    .task {
      guard Self.needsCode(
        sendsCode: sendsCode,
        isFirstRequest: codeLimiter.isFirstRequest(for: codeLimiterIdentifier),
        lastCodeWasSentHere: codeLimiter.lastCodeSentIdentifier == codeLimiterIdentifier
      ) else { return }
      await prepare()
    }
  }

  private var subtitle: LocalizedStringKey {
    switch factor.strategy {
    case .emailCode, .resetPasswordEmailCode:
      "Enter the code sent to your email to continue"
    case .phoneCode, .resetPasswordPhoneCode:
      "Enter the code sent to your phone to continue"
    default:
      "Enter the code generated by your authenticator app to continue"
    }
  }

  private var codeLimiterIdentifier: String {
    [flow.verification?.id ?? "", "\(stage)", factor.strategy.rawValue, factor.safeIdentifier ?? ""].joined(separator: ":")
  }

  /// Whether the screen sends a code when it appears. The server verifies only the code it sent
  /// last, so returning to this screen after another method sent one sends a new code here.
  static func needsCode(sendsCode: Bool, isFirstRequest: Bool, lastCodeWasSentHere: Bool) -> Bool {
    sendsCode && (isFirstRequest || !lastCodeWasSentHere)
  }
}

// MARK: - Actions

extension ReverificationCodeView {
  private func prepare() async {
    code = ""
    verificationState = .default

    guard let session = flow.session else { return }

    codeLimiter.forgetLastCodeSent()
    do {
      switch (factor.strategy, stage) {
      case (.emailCode, _):
        try await session.sendEmailCode(emailAddressId: factor.emailAddressId ?? "")
      case (.phoneCode, .firstFactor):
        try await session.sendPhoneCode(phoneNumberId: factor.phoneNumberId ?? "")
      case (.phoneCode, .secondFactor):
        try await session.sendMfaPhoneCode(phoneNumberId: factor.phoneNumberId ?? "")
      case (.resetPasswordEmailCode, _):
        try await session.sendResetPasswordEmailCode(emailAddressId: factor.emailAddressId ?? "")
      case (.resetPasswordPhoneCode, _):
        try await session.sendResetPasswordPhoneCode(phoneNumberId: factor.phoneNumberId ?? "")
      default:
        return
      }
      codeLimiter.recordCodeSent(for: codeLimiterIdentifier)
    } catch {
      guard !error.isCancellationError else { return }
      otpFieldIsFocused = false
      self.error = error
      ClerkLogger.error("Failed to send a reverification code", error: error)
    }
  }

  private func attempt(code: String) async -> OTPSubmissionDisposition {
    guard let session = flow.session else { return .stop }

    otpFieldState = .default
    verificationState = .verifying

    do {
      let verification = try await verify(session: session, code: code)
      guard !Task.isCancelled else {
        verificationState = .default
        return .stop
      }
      otpFieldIsFocused = false
      verificationState = .success
      await flow.handle(verification)
      return .stop
    } catch {
      guard !Task.isCancelled, !error.isCancellationError else {
        otpFieldState = .default
        verificationState = .default
        return .stop
      }
      if isPasswordReset, (error as? ClerkAPIError)?.meta?["param_name"] == "password" {
        otpFieldState = .default
        verificationState = .default
        flow.rejectNewPassword(error)
        return .stop
      }
      otpFieldState = .error
      verificationState = .error(error)
      if let clerkError = error as? ClerkAPIError, clerkError.meta?["param_name"] == nil {
        otpFieldIsFocused = false
        self.error = error
        ClerkLogger.error("Failed to verify a reverification code", error: error)
      }
      return error.otpSubmissionDisposition
    }
  }

  private func verify(session: Session, code: String) async throws -> SessionVerification {
    switch (factor.strategy, stage) {
    case (.emailCode, _):
      return try await session.verifyWithEmailCode(code: code)
    case (.phoneCode, .firstFactor):
      return try await session.verifyWithPhoneCode(code: code)
    case (.phoneCode, .secondFactor):
      return try await session.verifyWithMfaPhoneCode(code: code)
    case (.totp, _):
      return try await session.verifyWithTOTP(code: code)
    case (.resetPasswordEmailCode, _):
      return try await session.verifyWithResetPasswordEmailCode(
        code: code,
        newPassword: flow.newPassword,
        signOutOfOtherSessions: flow.signOutOfOtherSessions
      )
    case (.resetPasswordPhoneCode, _):
      return try await session.verifyWithResetPasswordPhoneCode(
        code: code,
        newPassword: flow.newPassword,
        signOutOfOtherSessions: flow.signOutOfOtherSessions
      )
    default:
      throw ClerkClientError(message: "Unknown code verification method. Please use another method.", localizationBundle: .module)
    }
  }
}

