import { test, expect, CLERK_TEST_CODE } from '../../fixtures.ts';
import { totp } from '../../totp.ts';

test('second factor and multi-factor with an authenticator app and a backup code', { timeout: 300_000 }, async ({ host, screen }) => {
  await host.useSettings({
    config: { 'auth_multi_factor.required_for_sign_up': true },
    environment: { 'user_settings.sign_up.mfa.required': true },
  });
  const user = await host.seedUser();
  await host.launch({ signedInAs: user, landsOn: host.app.signedOut });
  await host.tap(host.app.signInFullScreen);
  const authenticatorApp = screen.getByTestId('clerk.auth.sessionTask.setupMfa.authenticatorApp');
  await expect(authenticatorApp).toBeVisible({ timeout: 20_000 });
  await host.tap(authenticatorApp);
  const secret = screen.getByTestId('clerk.auth.sessionTask.totp.secret');
  await expect(secret).toBeVisible({ timeout: 20_000 });
  const secretText = (await secret.textContent()) ?? '';
  await host.tap(screen.getByTestId('clerk.auth.sessionTask.totp.continue'));
  await host.fill(screen.getByTestId('clerk.auth.sessionTask.totp.code'), totp(secretText, Date.now() / 1000));
  const backupCodesContinue = screen.getByTestId('clerk.auth.sessionTask.backupCodes.continue');
  await screen.scrollUntilVisible(backupCodesContinue);
  const backupCode = ((await screen.getByText(/^[a-z0-9]{8}$/).first().textContent()) ?? '').trim();
  await host.tap(backupCodesContinue);
  await host.expectSignedInAs(user, 30_000);

  await host.evidence('second factor: authenticator app, other methods, backup code', async () => {
    await host.tap(screen.getByTestId('e2e.home.reverify.secondFactor'));
    await expect(screen.getByText('Enter the code generated by your authenticator app to continue')).toBeVisible({ timeout: 20_000 });
    await host.screenshot('totp');
    await host.tap(screen.getByTestId('clerk.reverification.useAnotherMethod'));
    const backup = screen.getByTestId('clerk.reverification.alternativeMethod.backup_code');
    await expect(backup).toBeVisible({ timeout: 20_000 });
    await host.screenshot('alternatives-second-factor');
    await host.tap(backup);
    const backupField = screen.getByTestId('clerk.reverification.backupCode');
    await expect(backupField).toBeVisible({ timeout: 20_000 });
    await host.screenshot('backup-code');
    await host.fill(backupField, backupCode);
    await host.tap(screen.getByTestId('clerk.reverification.continue'));
    await expect(screen.getByTestId('e2e.home.reverificationResult')).toHaveText('Reverified', { timeout: 30_000 });
  });

  await host.evidence('multi-factor: email code, then the authenticator app', async () => {
    await host.tap(screen.getByTestId('e2e.home.reverify.multiFactor'));
    const code = screen.getByTestId('clerk.reverification.code');
    await expect(screen.getByText(user.email)).toBeVisible({ timeout: 20_000 });
    await host.screenshot('multi-factor-first-step');
    await host.fill(code, CLERK_TEST_CODE);
    await expect(screen.getByText('Enter the code generated by your authenticator app to continue')).toBeVisible({ timeout: 20_000 });
    await host.screenshot('multi-factor-second-step');
    await host.fill(screen.getByTestId('clerk.reverification.code'), totp(secretText, Date.now() / 1000 + 30));
    await expect(screen.getByTestId('e2e.home.reverificationResult')).toHaveText('Reverified', { timeout: 30_000 });
  });
});
